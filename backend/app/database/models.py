"""
Database Models — SQLAlchemy ORM
Tables: users, aws_accounts, audit_logs, budgets, notification_preferences
"""

import uuid
from datetime import datetime
from sqlalchemy import (
    Column, String, Boolean, DateTime, Float,
    ForeignKey, Text, Enum, Integer
)
from sqlalchemy.orm import relationship
from sqlalchemy.dialects.postgresql import UUID
from app.database.database import Base


def generate_uuid():
    return str(uuid.uuid4())


# ── Users ─────────────────────────────────────────────────────────────────────
class User(Base):
    __tablename__ = "users"

    id           = Column(String(36), primary_key=True, default=generate_uuid)
    cognito_sub  = Column(String(255), unique=True, nullable=False, index=True)
    email        = Column(String(255), unique=True, nullable=False, index=True)
    full_name    = Column(String(255), nullable=True)
    is_active    = Column(Boolean, default=True)
    created_at   = Column(DateTime, default=datetime.utcnow)
    updated_at   = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    # Relationships
    aws_accounts          = relationship("AWSAccount", back_populates="user", cascade="all, delete-orphan")
    audit_logs            = relationship("AuditLog", back_populates="user")
    budgets               = relationship("Budget", back_populates="user", cascade="all, delete-orphan")
    notification_prefs    = relationship("NotificationPreference", back_populates="user", uselist=False)

    def to_dict(self):
        return {
            "id":         self.id,
            "email":      self.email,
            "full_name":  self.full_name,
            "is_active":  self.is_active,
            "created_at": self.created_at.isoformat() if self.created_at else None,
        }


# ── AWS Accounts ──────────────────────────────────────────────────────────────
class AWSAccount(Base):
    __tablename__ = "aws_accounts"

    id                = Column(String(36), primary_key=True, default=generate_uuid)
    user_id           = Column(String(36), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True)
    account_name      = Column(String(255), nullable=False)           # "Production", "Dev"
    aws_account_id    = Column(String(12), nullable=False)            # "123456789012"
    role_arn          = Column(String(255), nullable=False)            # "arn:aws:iam::123...role/FinOpsRole"
    external_id       = Column(String(255), nullable=False)            # UUID generated by platform
    default_region    = Column(String(50), default="us-east-1")
    is_active         = Column(Boolean, default=True)
    connection_status = Column(
        Enum("pending", "connected", "failed", "disconnected", name="connection_status"),
        default="pending"
    )
    last_synced_at    = Column(DateTime, nullable=True)
    created_at        = Column(DateTime, default=datetime.utcnow)
    updated_at        = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    # Relationships
    user       = relationship("User", back_populates="aws_accounts")
    audit_logs = relationship("AuditLog", back_populates="aws_account")
    budgets    = relationship("Budget", back_populates="aws_account")

    def to_dict(self):
        return {
            "id":               self.id,
            "account_name":     self.account_name,
            "aws_account_id":   self.aws_account_id,
            "role_arn":         self.role_arn,
            "external_id":      self.external_id,
            "default_region":   self.default_region,
            "is_active":        self.is_active,
            "connection_status": self.connection_status,
            "last_synced_at":   self.last_synced_at.isoformat() if self.last_synced_at else None,
            "created_at":       self.created_at.isoformat() if self.created_at else None,
        }


# ── Audit Logs ────────────────────────────────────────────────────────────────
class AuditLog(Base):
    __tablename__ = "audit_logs"

    id               = Column(String(36), primary_key=True, default=generate_uuid)
    user_id          = Column(String(36), ForeignKey("users.id"), nullable=False, index=True)
    aws_account_id   = Column(String(36), ForeignKey("aws_accounts.id"), nullable=True, index=True)
    action           = Column(String(100), nullable=False)             # "STOP_EC2", "DELETE_EBS"
    resource_type    = Column(String(50), nullable=True)               # "EC2", "EBS"
    resource_id      = Column(String(255), nullable=True)              # "i-abc123"
    description      = Column(Text, nullable=True)
    estimated_saving = Column(Float, nullable=True)
    status           = Column(
        Enum("pending", "success", "failed", "dry_run", name="audit_status"),
        default="pending"
    )
    error_message    = Column(Text, nullable=True)
    metadata_json    = Column(Text, nullable=True)                     # JSON string for extra data
    created_at       = Column(DateTime, default=datetime.utcnow, index=True)

    # Relationships
    user        = relationship("User", back_populates="audit_logs")
    aws_account = relationship("AWSAccount", back_populates="audit_logs")

    def to_dict(self):
        return {
            "id":               self.id,
            "action":           self.action,
            "resource_type":    self.resource_type,
            "resource_id":      self.resource_id,
            "description":      self.description,
            "estimated_saving": self.estimated_saving,
            "status":           self.status,
            "error_message":    self.error_message,
            "created_at":       self.created_at.isoformat() if self.created_at else None,
        }


# ── Budgets ───────────────────────────────────────────────────────────────────
class Budget(Base):
    __tablename__ = "budgets"

    id               = Column(String(36), primary_key=True, default=generate_uuid)
    user_id          = Column(String(36), ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    aws_account_id   = Column(String(36), ForeignKey("aws_accounts.id", ondelete="CASCADE"), nullable=True)
    budget_name      = Column(String(255), nullable=False)
    monthly_limit    = Column(Float, nullable=False)
    warning_pct      = Column(Float, default=80.0)
    critical_pct     = Column(Float, default=90.0)
    emergency_pct    = Column(Float, default=100.0)
    is_active        = Column(Boolean, default=True)
    created_at       = Column(DateTime, default=datetime.utcnow)

    user        = relationship("User", back_populates="budgets")
    aws_account = relationship("AWSAccount", back_populates="budgets")

    def to_dict(self):
        return {
            "id":             self.id,
            "budget_name":    self.budget_name,
            "monthly_limit":  self.monthly_limit,
            "warning_pct":    self.warning_pct,
            "critical_pct":   self.critical_pct,
            "emergency_pct":  self.emergency_pct,
            "is_active":      self.is_active,
            "created_at":     self.created_at.isoformat() if self.created_at else None,
        }


# ── Notification Preferences ──────────────────────────────────────────────────
class NotificationPreference(Base):
    __tablename__ = "notification_preferences"

    id                  = Column(String(36), primary_key=True, default=generate_uuid)
    user_id             = Column(String(36), ForeignKey("users.id", ondelete="CASCADE"), unique=True)
    email_enabled       = Column(Boolean, default=True)
    sns_enabled         = Column(Boolean, default=False)
    sns_topic_arn       = Column(String(255), nullable=True)
    slack_enabled       = Column(Boolean, default=False)
    slack_webhook_url   = Column(String(500), nullable=True)
    notify_anomalies    = Column(Boolean, default=True)
    notify_budget       = Column(Boolean, default=True)
    notify_waste        = Column(Boolean, default=True)
    notify_remediation  = Column(Boolean, default=True)
    notify_security     = Column(Boolean, default=True)
    created_at          = Column(DateTime, default=datetime.utcnow)
    updated_at          = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    user = relationship("User", back_populates="notification_prefs")

    def to_dict(self):
        return {
            "id":                 self.id,
            "email_enabled":      self.email_enabled,
            "sns_enabled":        self.sns_enabled,
            "slack_enabled":      self.slack_enabled,
            "notify_anomalies":   self.notify_anomalies,
            "notify_budget":      self.notify_budget,
            "notify_waste":       self.notify_waste,
            "notify_remediation": self.notify_remediation,
            "notify_security":    self.notify_security,
        }
